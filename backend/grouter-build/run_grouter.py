"""Entry point: launch the REAL gRouter wired into the portable fabric.

Reads ROUTER_CONFIG (the same per-router wiring our frontend compiler already emits)
and turns it into the gRouter's NATIVE config — `ifconfig add tun…` + `route add…`,
using the legacy `tun` interface, which is a userspace UDP socket. This is the seam
where the new portable fabric meets the real C router.

ROUTER_CONFIG = {
  "name": "r1",
  "ifaces": [
    {"ip": "10.0.1.1/24", "mac": "02:..:01", "port": {"peer_host": "m1", "peer_port": 5000}},
    ...
  ]
}
"""
from __future__ import annotations

import glob
import ipaddress
import os
import signal
import socket
import subprocess
import sys
import time

GROUTER = os.environ.get("GROUTER_BIN", "/usr/local/bin/grouter")


#: How long to wait for a peer's container name to appear in Docker DNS before giving up.
RESOLVE_S = float(os.environ.get("GINI_PEER_RESOLVE_S", "120"))
#: What an unresolved peer becomes. The C router learns the real address from the first datagram
#: the peer sends it (tun.c, tun_recvfrom), so a placeholder heals; a hostname never could.
UNRESOLVED = "0.0.0.0"


#: The router's name, for log lines (set by main). A module global rather than an argument so
#: the tests that monkeypatch `resolve` with a one-argument lambda keep working.
ROUTER_NAME = "router"


def resolve(host: str, deadline_s: float | None = None) -> str:
    """The peer container's address, waiting for Docker DNS to know it.

    Compose starts a lab's containers in no particular order, and a name resolves only once
    that container is attached to the network. On a slow laptop (Windows, Docker Desktop,
    eight containers) the gap can run well past ten seconds. This used to try for ten and then
    hand back the bare HOSTNAME -- which `ifconfig add -dstip` parses with sscanf, leaving the
    destination as whatever was on the stack. The interface still received (its socket was
    bound), so the router heard every neighbour that started after it and was heard by none
    of them: RIP tables with every route pointing one way, pings that never came back, and
    "it works sometimes" depending on which container won the start. Now the wait is long,
    says what it is waiting for, and gives up to a placeholder the router can recover from.
    """
    name = ROUTER_NAME
    limit = RESOLVE_S if deadline_s is None else deadline_s
    t0 = time.monotonic()
    said = 0.0
    while True:
        try:
            return socket.gethostbyname(host)
        except OSError:
            waited = time.monotonic() - t0
            if waited >= limit:
                print(f"[{name}] WARNING: peer '{host}' never appeared in Docker DNS after "
                      f"{waited:.0f} s; the link to it will come up when it speaks first.",
                      file=sys.stderr)
                return UNRESOLVED
            if waited - said >= 5:
                print(f"[{name}] waiting for peer '{host}' to come up ({waited:.0f} s)",
                      file=sys.stderr)
                said = waited
            time.sleep(0.5)


def build_config(cfg: dict) -> str:
    # OpenFlow (OVS) mode: the gRouter is an L2 switch programmed by a controller, so
    # the tun ports come up (with link-local placeholder addresses) but get NO routes —
    # frames are switched by the flow table, not routed.
    openflow = bool(cfg.get("openflow"))
    lines = ["# generated by run_grouter.py — gRouter native config"]
    routes = []
    for i, itf in enumerate(cfg["ifaces"], start=1):     # tun0 is reserved for tap
        dev = f"tun{i}"
        iface = ipaddress.ip_interface(itf["ip"])
        ip = str(iface.ip)
        peer = itf["port"]
        peer_ip = resolve(peer["peer_host"])
        # Literal-port wiring: the router binds its local UDP port (bind_port) and
        # the peer (the machine's shuttle) sends FROM peer_port. -srcport makes the
        # tun driver use these literal ports instead of the legacy BASEPORTNUM/name
        # formula, so the portable fabric interoperates with the real C router.
        srcport = peer.get("bind_port")
        # -srcport is optional and parsed in the trailing-args region, so it must
        # come AFTER -addr/-hwaddr (the fixed parser expects -addr after -dstport).
        srcport_opt = f" -srcport {srcport}" if srcport is not None else ""
        # -netmask: the router kept no mask and assumed /24 everywhere that needed one; give it
        # the real one. A trailing option, after -srcport -- the parser's fixed part ends at
        # -hwaddr -- and an older router image ignores it.
        # -metric: the drawn link's routing cost (the compiler puts it in port["link"]), for a
        # routing protocol to read through Lua interfaces(). Only when it is not 1, so a plain
        # lab's config is unchanged; an older router image ignores the option.
        cost = (peer.get("link") or {}).get("cost", 1)
        try:
            cost = int(cost)
        except (TypeError, ValueError):
            cost = 1
        metric_opt = f" -metric {cost}" if 1 < cost <= 15 else ""
        lines.append(
            f"ifconfig add {dev} -dstip {peer_ip} -dstport {peer['peer_port']} "
            f"-addr {ip} -hwaddr {itf['mac']} -mtu 1400{srcport_opt} "
            f"-netmask {iface.network.netmask}{metric_opt}"
        )
        if not openflow:
            routes.append(
                f"route add -dev {dev} -net {iface.network.network_address} "
                f"-netmask {iface.network.netmask}"
            )
    # static inter-router routes (the compiler computes next-hops; no routing protocol)
    for rt in cfg.get("routes", []):
        routes.append(
            f"route add -dev tun{rt['dev']} -net {rt['net']} "
            f"-netmask {rt['mask']} -gw {rt['gw']}"
        )
    lines += routes
    # link delay set in the Router Lab (compiler: RouterSpec.delay) -- the same `delay` command
    # the Lab sends live, so a tuned delay survives the next Run instead of vanishing.
    for side in ("ingress", "egress"):
        d = (cfg.get("delay") or {}).get(side)
        if d:
            base, jit, corr = (list(d) + [0, 0, 0])[:3]
            lines.append(f"delay {side} {float(base):g} {float(jit):g} {float(corr):g}")
    return "\n".join(lines) + "\n"


def grouter_cmd(conf: str, confdir: str, name: str, openflow_port: int | None = None) -> list[str]:
    """The exact argv used to launch the gRouter. Kept as a function so a test can
    assert the option spelling (the binary only accepts --config / --confpath / -p).
    In OVS mode we add --openflow=<port>, which flips the gRouter into an OpenFlow 1.0
    switch that connects to the controller named by GINI_OF_CONTROLLER."""
    argv = [GROUTER, "--config=" + conf, "--confpath=" + confdir]
    if openflow_port is not None:
        argv.append(f"--openflow={openflow_port}")
    argv.append(name)
    return argv


#: Where the router's crash reports and its rotating log go: /captures is the host's
#: ~/.gini/captures, bind-mounted by gBuilder, and it survives Stop. The container's own log does
#: not -- Stop is `compose down`, which deletes the container and its log with it, so a crash was
#: only ever diagnosable by someone who thought to run `docker logs` BEFORE pressing Stop.
CRASH_DIR = os.environ.get("GINI_CRASH_DIR", "/captures")
#: Size at which <name>.log rolls over to <name>.log.1. Two files, so at most twice this on disk.
LOG_BYTES = int(os.environ.get("GINI_ROUTER_LOG_BYTES", str(1 << 20)))
#: Crash reports kept per router name; older ones are deleted at start and after a crash.
KEEP_REPORTS = 5


def crash_dir() -> str | None:
    """CRASH_DIR if this container can write there, else None (no file, stderr only)."""
    d = CRASH_DIR
    return d if d and os.path.isdir(d) and os.access(d, os.W_OK) else None


def keep_newest_reports(d: str, name: str, keep: int = KEEP_REPORTS) -> None:
    """Delete all but the newest `keep` <name>-crash-*.txt in d. Capped, like everything here."""
    reports = sorted(glob.glob(os.path.join(d, f"{name}-crash-*.txt")),
                     key=lambda p: os.path.getmtime(p), reverse=True)
    for old in reports[keep:]:
        try:
            os.remove(old)
        except OSError:
            pass


class RotatingTee:
    """Copy the router's output to the container's stdout AND to <dir>/<name>.log.

    The log is capped: past `limit` bytes it is renamed to <name>.log.1 (replacing the previous
    one) and a fresh file starts, so the disk never holds more than 2 x limit for a router. The
    point is the lines just before a crash, which a crash report's backtrace does not show --
    what the router printed while it was still alive.
    """

    def __init__(self, d: str, name: str, limit: int = LOG_BYTES, out=None):
        self.path = os.path.join(d, f"{name}.log")
        self.limit = limit
        self.out = out if out is not None else sys.stdout.buffer
        self.f = None
        self._open()

    def _open(self) -> None:
        try:
            self.f = open(self.path, "ab")
        except OSError:
            self.f = None

    def write(self, chunk: bytes) -> None:
        try:
            self.out.write(chunk)
            self.out.flush()
        except (OSError, ValueError):
            pass
        if self.f is None:
            return
        try:
            self.f.write(chunk)
            self.f.flush()
            if self.f.tell() >= self.limit:
                self.f.close()
                os.replace(self.path, self.path + ".1")
                self._open()
        except OSError:
            self.f = None              # a full disk must not take the router down with it

    def close(self) -> None:
        if self.f is not None:
            self.f.close()


def pump(fd: int, tee: RotatingTee) -> None:
    """Copy fd to tee until EOF (the router exited and its end of the pipe closed)."""
    while True:
        try:
            chunk = os.read(fd, 65536)
        except InterruptedError:
            continue
        except OSError:
            return
        if not chunk:
            return
        tee.write(chunk)


def exit_reason(rc: int | None) -> str:
    """`crashed (SIGSEGV)` for a signal, `exited (1)` otherwise."""
    if rc is not None and rc < 0:
        try:
            return f"crashed ({signal.Signals(-rc).name})"
        except ValueError:
            return f"crashed (signal {-rc})"
    return f"exited ({rc})"


def newest_report(d: str, name: str, since: float) -> str | None:
    reports = [p for p in glob.glob(os.path.join(d, f"{name}-crash-*.txt"))
               if os.path.getmtime(p) >= since - 1]
    return max(reports, key=os.path.getmtime) if reports else None


def clear_stale_pidfile(confdir: str, name: str) -> None:
    """Remove <confdir>/<name>.pid before starting.

    The gRouter refuses to start when that file names a live process — sound on a workstation,
    WRONG inside a container. A restarted container begins its PID namespace at 1 again, so the
    number in a leftover pid file is near-certain to belong to some new process (ttyd, this
    script, the router itself), `kill(pid, 0)` succeeds, and the router aborts:

        r1: fatal: [makePIDFile]:: Another router is still running under: /run/r1.pid
        [r1] gRouter exited (1); stopping container.

    which then loops: the container restarts, finds the same file, and dies again. One crash
    became a router that could never come back.

    Deleting it here is safe precisely because of where "here" is: this script IS the container's
    entrypoint, so reaching this line means the container has just started and no previous router
    of ours survived. The C-side liveness check stays as it is — it is still right for someone
    running two routers on one host outside a container.
    """
    path = os.path.join(confdir, f"{name}.pid")
    try:
        with open(path) as f:
            stale = f.read().strip()
    except OSError:
        return                                     # no pid file: the ordinary case
    try:
        os.remove(path)
        print(f"[{name}] removed stale pid file {path} (held pid {stale}); the container "
              f"restarted, so that pid belongs to something else now.", file=sys.stderr)
    except OSError as e:
        print(f"[{name}] WARNING: could not remove {path}: {e}", file=sys.stderr)


def main() -> int:
    raw = os.environ.get("ROUTER_CONFIG")
    if not raw:
        print("ROUTER_CONFIG not set", file=sys.stderr)
        return 2
    import json
    cfg = json.loads(raw)
    name = cfg.get("name", "r1")
    global ROUTER_NAME
    ROUTER_NAME = name

    confdir = "/run"
    conf = os.path.join(confdir, f"{name}.conf")
    with open(conf, "w") as f:
        f.write(build_config(cfg))
    print(f"[{name}] config:\n{open(conf).read()}", file=sys.stderr)

    clear_stale_pidfile(confdir, name)

    # launch the real gRouter, sourcing the generated config (OVS mode -> --openflow)
    of = cfg.get("openflow")
    of_port = of.get("port") if isinstance(of, dict) else (6633 if of else None)
    cmd = grouter_cmd(conf, confdir, name, openflow_port=of_port)
    print(f"[{name}] exec: {' '.join(cmd)}", file=sys.stderr)
    cdir = crash_dir()
    started = time.time()
    if cdir:
        keep_newest_reports(cdir, name)
        sys.stderr.flush()
        tee = RotatingTee(cdir, name)
        tee.write(f"==== {name} started {time.strftime('%Y-%m-%d %H:%M:%S')} ====\n".encode())
        proc = subprocess.Popen(cmd, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                                stderr=subprocess.STDOUT,
                                env={**os.environ, "GR_CRASH_DIR": cdir})
        pump(proc.stdout.fileno(), tee)
        rc = proc.wait()
        tee.write(f"==== {name} {exit_reason(rc)} {time.strftime('%Y-%m-%d %H:%M:%S')} ====\n"
                  .encode())
        tee.close()
        report = newest_report(cdir, name, started) if rc is not None and rc < 0 else None
        if report:
            keep_newest_reports(cdir, name)
            print(f"[{name}] gRouter {exit_reason(rc)}; crash report: "
                  f"{os.path.basename(report)} in GINI's captures folder (~/.gini/captures)",
                  file=sys.stderr)
    else:
        proc = subprocess.Popen(cmd, stdin=subprocess.DEVNULL)
        rc = proc.wait()
    # Do NOT silently hold a dead router "running" — that masks failures and shows a
    # green node in the GUI while nothing forwards. Propagate the exit so the container
    # stops and the node turns red. Set GINI_HOLD_ON_EXIT=1 to keep it up for debugging.
    if os.environ.get("GINI_HOLD_ON_EXIT") == "1":
        print(f"[{name}] gRouter {exit_reason(rc)}; holding container (GINI_HOLD_ON_EXIT).",
              file=sys.stderr)
        while True:
            time.sleep(3600)
    print(f"[{name}] gRouter {exit_reason(rc)}; stopping container.", file=sys.stderr)
    return rc if rc is not None else 1


if __name__ == "__main__":
    raise SystemExit(main())
