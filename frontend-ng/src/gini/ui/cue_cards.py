"""Cue Cards — a launch-time feature tour for gBuilder.

A simple card deck: each card shows a real screenshot of the feature (curated portions of
the actual UI, generated by scripts/gen_cue_shots.py into assets/cue/<kind>.png), a title,
and a short explanation. Navigate with the ‹ / › arrows or the keyboard. "Don't show at
launch" + the Settings Help tab control whether it auto-opens; reopen from Help → Feature
Tour.
"""
from __future__ import annotations

import re
from pathlib import Path

from PySide6.QtCore import QRectF, Qt
from PySide6.QtGui import QColor, QFont, QPainter, QPixmap
from PySide6.QtWidgets import (
    QCheckBox, QDialog, QHBoxLayout, QLabel, QPushButton, QVBoxLayout, QWidget,
)

_CUE_DIR = Path(__file__).resolve().parent / "assets" / "cue"


def _theme_slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]", "", (name or "dark").lower()) or "dark"


def _cue_candidates(cue_dir: Path, slug: str, dark: bool, kind: str) -> list[Path]:
    """Screenshot search order: the running theme's own shots first, then its
    light/dark *family* (so Sand/Blue/Green reuse the Light set), then dark, then
    a legacy flat file."""
    family = "dark" if dark else "light"
    return [cue_dir / slug / f"{kind}.png",
            cue_dir / family / f"{kind}.png",
            cue_dir / "dark" / f"{kind}.png",
            cue_dir / f"{kind}.png"]


