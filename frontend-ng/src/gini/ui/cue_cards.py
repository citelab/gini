def _qcolor(spec) -> QColor:
    if isinstance(spec, QColor):
        return spec
    if isinstance(spec, str) and spec.startswith("rgba("):
        n = [int(float(x)) for x in spec[5:-1].split(",")]
        return QColor(n[0], n[1], n[2], n[3] if len(n) > 3 else 255)
    return QColor(spec)


class CardArt(QWidget):
    """Shows the current card's screenshot, scaled to fit (keeping aspect), centered."""

    def __init__(self, theme) -> None:
        super().__init__()
        self.theme = theme
        self._pix: QPixmap | None = None
        self._kind = "welcome"
        self.setMinimumHeight(320)

    def set_kind(self, kind: str) -> None:
        self._kind = kind
        # prefer the screenshot for the running theme; fall back within the light/dark
        # family (so Sand/Blue/Green reuse the Light shots), then dark, then legacy flat
        slug = _theme_slug(self.theme.theme.name)
        pix = QPixmap()
        for cand in _cue_candidates(_CUE_DIR, slug, self.theme.theme.dark, kind):
            if cand.exists():
                pix = QPixmap(str(cand))
                if not pix.isNull():
                    break
        self._pix = pix if not pix.isNull() else None
        self.update()

    def paintEvent(self, _e) -> None:
        t = self.theme.theme
        p = QPainter(self)
        p.setRenderHint(QPainter.SmoothPixmapTransform, True)
        p.setRenderHint(QPainter.Antialiasing, True)
        r = QRectF(self.rect())
        p.fillRect(r, _qcolor(getattr(t, "panel", t.bg)))
        if self._pix is not None and not self._pix.isNull():
            # fit the full-resolution pixmap into the available area keeping aspect, and let
            # the painter scale it straight to device pixels — pre-scaling to logical size
            # first would throw away resolution and blur on Retina/HiDPI displays.
            avail = r.adjusted(12, 12, -12, -12)
            pw, ph = self._pix.width(), self._pix.height()
            s = min(avail.width() / pw, avail.height() / ph)
            tw, th = pw * s, ph * s
            target = QRectF(r.center().x() - tw / 2, r.center().y() - th / 2, tw, th)
            p.drawPixmap(target, self._pix, QRectF(0, 0, pw, ph))
        else:                                          # graceful fallback if an image is missing
            p.setPen(_qcolor(getattr(t, "muted", t.text)))
            f = QFont(); f.setPointSize(13); p.setFont(f)
            p.drawText(r, Qt.AlignCenter, self._kind)
        p.end()


class CueCards(QDialog):
    """The card-deck dialog. `persist` is called after the user changes the launch pref."""

    def __init__(self, parent, theme, settings, cards=FEATURE_CARDS, persist=None) -> None:
        super().__init__(parent)
        self.setWindowTitle("gBuilder — Feature Tour")
        self.setModal(True)
        self.setMinimumSize(760, 660)
        self.theme = theme
        self.settings = settings
        self._cards = list(cards)
        self._persist = persist or (lambda: None)
        self._i = 0

        t = theme.theme
        self.setStyleSheet(
            f"QDialog {{ background: {_color(t.bg)}; }}"
            f"QLabel {{ color: {_color(t.text)}; }}"
            f"QLabel#Body {{ color: {_color(getattr(t, 'muted', t.text))}; font-size: 15px; }}")

        lay = QVBoxLayout(self)
        lay.setContentsMargins(20, 20, 20, 16)
        lay.setSpacing(12)
        self.art = CardArt(theme)
        lay.addWidget(self.art, 1)
        self.title = QLabel()
        tf = QFont(); tf.setBold(True); tf.setPointSize(21)
        self.title.setFont(tf)
        lay.addWidget(self.title)
        self.body = QLabel(); self.body.setObjectName("Body"); self.body.setWordWrap(True)
        self.body.setMinimumHeight(74)
        lay.addWidget(self.body)

        footer = QHBoxLayout()
        self.dont = QCheckBox("Don't show at launch")
        self.dont.setChecked(not settings.show_help_on_launch)
        self.dont.toggled.connect(self._on_dont)
        footer.addWidget(self.dont)
        footer.addStretch(1)
        self.back = QPushButton("‹ Back"); self.back.clicked.connect(lambda: self._go(-1))
        self.count = QLabel(); self.count.setObjectName("Body")
        self.next = QPushButton("Next ›"); self.next.clicked.connect(lambda: self._go(1))
        done = QPushButton("Done"); done.setObjectName("Accent"); done.clicked.connect(self.accept)
        for w in (self.back, self.count, self.next, done):
            footer.addWidget(w)
        lay.addLayout(footer)

        self._show_card()

    # -- navigation --------------------------------------------------------- #
    def _go(self, delta: int) -> None:
        self._i = max(0, min(len(self._cards) - 1, self._i + delta))
        self._show_card()

    def _show_card(self) -> None:
        kind, title, body = self._cards[self._i]
        self.art.set_kind(kind)
        self.title.setText(title)
        self.body.setText(body)
        self.count.setText(f"{self._i + 1} / {len(self._cards)}")
        self.back.setEnabled(self._i > 0)
        self.next.setEnabled(self._i < len(self._cards) - 1)

    def keyPressEvent(self, e) -> None:
        if e.key() in (Qt.Key_Right, Qt.Key_Space):
            self._go(1)
        elif e.key() == Qt.Key_Left:
            self._go(-1)
        elif e.key() == Qt.Key_Escape:
            self.accept()
        else:
            super().keyPressEvent(e)

    # -- preference --------------------------------------------------------- #
    def _on_dont(self, checked: bool) -> None:
        self.settings.show_help_on_launch = not checked
        self._persist()


def _color(spec) -> str:
    return _qcolor(spec).name()
